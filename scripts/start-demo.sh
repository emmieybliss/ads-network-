#!/usr/bin/env bash
# Start the local BlissNova demo with Docker Compose.
#   web + dashboards  http://localhost:3000
#   API               http://localhost:4000
#   demo publisher    http://localhost:3100
# First run generates .env.demo (random secrets and demo password, gitignored).
set -euo pipefail
cd "$(dirname "$0")/.."

command -v docker >/dev/null || { echo "Docker is not installed. Install Docker Desktop (or Docker Engine) first."; exit 1; }
docker info >/dev/null 2>&1 || { echo "Docker is installed but not running. Start Docker Desktop and try again."; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "Docker Compose v2 is required ('docker compose')."; exit 1; }

rand() { head -c "$1" /dev/urandom | base64 | tr -d '\n'; }
alnum() { head -c 64 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c "$1"; }

if [ ! -f .env.demo ]; then
  echo "Creating .env.demo with fresh random secrets..."
  umask 077
  cat > .env.demo <<ENV
# Generated by scripts/start-demo.sh for the LOCAL DEMO only. Never use in production.
POSTGRES_PASSWORD=$(alnum 24)
APP_SECRET=$(rand 48)
ENCRYPTION_KEY=$(rand 32)
TRACKING_TOKEN_KEYS=k1:$(rand 32)
SEED_PASSWORD=Demo-$(alnum 12)
DEMO_SITE_KEY=pk_DemoLocalPublisherSite01
ENV
fi

docker compose --env-file .env.demo up -d --build "$@"

echo "Waiting for the services to report healthy..."
for i in $(seq 1 90); do
  web=$(curl -fsS -o /dev/null -w '%{http_code}' http://localhost:3000/ 2>/dev/null || true)
  api=$(curl -fsS -o /dev/null -w '%{http_code}' http://localhost:4000/ready 2>/dev/null || true)
  site=$(curl -fsS -o /dev/null -w '%{http_code}' http://localhost:3100/healthz 2>/dev/null || true)
  if [ "$web" = 200 ] && [ "$api" = 200 ] && [ "$site" = 200 ]; then ready=1; break; fi
  sleep 2
done
if [ "${ready:-}" != 1 ]; then
  echo "The demo did not become healthy in time. See: docker compose --env-file .env.demo ps / logs (docs/TROUBLESHOOTING.md)."
  exit 1
fi

pw=$(grep '^SEED_PASSWORD=' .env.demo | cut -d= -f2-)
cat <<MSG

BlissNova demo is running.
  Website and dashboards   http://localhost:3000
  API (health, OpenAPI)    http://localhost:4000/ready   http://localhost:3000/docs/api
  Demo publisher site      http://localhost:3100

  Logins (demo accounts)   admin@example.com / advertiser@example.com / publisher@example.com
  Password                 $pw   (stored in .env.demo)

All accounts, campaigns and statistics are fictional demo data.
Stop with scripts/stop-demo.sh, wipe and re-seed with scripts/reset-demo.sh.
MSG
