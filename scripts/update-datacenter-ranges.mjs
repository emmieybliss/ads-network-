#!/usr/bin/env node
/**
 * Refreshes the bundled list of cloud and hosting IP ranges used by the
 * invalid-traffic filter (traffic from servers is not people).
 *
 * Every source is a list the provider itself publishes for free. A source
 * that cannot be reached is skipped with a warning; at least one must load.
 *
 *   node scripts/update-datacenter-ranges.mjs
 *
 * Writes packages/tracking/src/datacenter-ranges.generated.ts. Commit the result.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, '..', 'packages', 'tracking', 'src', 'datacenter-ranges.generated.ts');

const csvFirstColumn = (text) => text.split(/\r?\n/).filter((l) => l && !l.startsWith('#')).map((l) => l.split(',')[0].trim());

const SOURCES = [
  { name: 'Amazon Web Services', url: 'https://ip-ranges.amazonaws.com/ip-ranges.json', parse: (t) => { const j = JSON.parse(t); return [...j.prefixes.map((p) => p.ip_prefix), ...j.ipv6_prefixes.map((p) => p.ipv6_prefix)]; } },
  { name: 'Google Cloud', url: 'https://www.gstatic.com/ipranges/cloud.json', parse: (t) => JSON.parse(t).prefixes.map((p) => p.ipv4Prefix ?? p.ipv6Prefix) },
  { name: 'Oracle Cloud', url: 'https://docs.oracle.com/en-us/iaas/tools/public_ip_ranges.json', parse: (t) => JSON.parse(t).regions.flatMap((r) => r.cidrs.map((c) => c.cidr)) },
  { name: 'DigitalOcean', url: 'https://digitalocean.com/geo/google.csv', parse: csvFirstColumn },
  { name: 'Linode (Akamai)', url: 'https://geoip.linode.com/', parse: csvFirstColumn },
];

// ---- CIDR maths (IPv4 as numbers, IPv6 as BigInt) --------------------------------

function parseCidr(c) {
  const [addr, bitsStr] = c.trim().split('/');
  if (!addr || bitsStr === undefined) return null;
  const bits = Number(bitsStr);
  if (addr.includes(':')) {
    const v = v6ToBig(addr);
    if (v === null || !(bits >= 0 && bits <= 128)) return null;
    const size = 1n << BigInt(128 - bits);
    const start = (v / size) * size;
    return { v6: true, start, end: start + size - 1n };
  }
  const p = addr.split('.').map(Number);
  if (p.length !== 4 || p.some((x) => !(x >= 0 && x <= 255)) || !(bits >= 0 && bits <= 32)) return null;
  const v = BigInt(((p[0] << 24) >>> 0) + (p[1] << 16) + (p[2] << 8) + p[3]);
  const size = 1n << BigInt(32 - bits);
  const start = (v / size) * size;
  return { v6: false, start, end: start + size - 1n };
}

function v6ToBig(a) {
  const [head, tail] = a.split('::');
  const h = head ? head.split(':') : [];
  const t = tail !== undefined ? (tail ? tail.split(':') : []) : [];
  const groups = tail !== undefined ? [...h, ...Array(8 - h.length - t.length).fill('0'), ...t] : h;
  if (groups.length !== 8) return null;
  let v = 0n;
  for (const g of groups) {
    const n = parseInt(g || '0', 16);
    if (!(n >= 0 && n <= 0xffff)) return null;
    v = (v << 16n) | BigInt(n);
  }
  return v;
}

function merge(ranges) {
  ranges.sort((a, b) => (a.start < b.start ? -1 : a.start > b.start ? 1 : 0));
  const out = [];
  for (const r of ranges) {
    const last = out[out.length - 1];
    if (last && r.start <= last.end + 1n) { if (r.end > last.end) last.end = r.end; } else out.push({ ...r });
  }
  return out;
}

// Ranges are stored as base-36 "start-end" pairs: compact, and exact for both families.
const enc = (r) => `${r.start.toString(36)}-${r.end.toString(36)}`;

const v4 = [];
const v6 = [];
const loaded = [];
for (const s of SOURCES) {
  try {
    const res = await fetch(s.url, { signal: AbortSignal.timeout(30_000), headers: { 'user-agent': 'blissnova-ivt-ranges-updater' } });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const list = s.parse(await res.text());
    let n = 0;
    for (const c of list) {
      const r = c && parseCidr(c);
      if (!r) continue;
      (r.v6 ? v6 : v4).push(r);
      n++;
    }
    loaded.push(`${s.name} (${n} prefixes)`);
    console.log(`loaded ${s.name}: ${n} prefixes`);
  } catch (err) {
    console.warn(`skipped ${s.name}: ${err.message}`);
  }
}
if (!loaded.length) {
  console.error('No source could be loaded; the existing list was left unchanged.');
  process.exit(1);
}
const m4 = merge(v4);
const m6 = merge(v6);
const today = new Date().toISOString().slice(0, 10);
const chunk = (arr) => arr.map(enc).join(' ').replace(/(.{1,110})(\s|$)/g, '$1\n').trim().split('\n').map((l) => `  '${l} '`).join(',\n');
writeFileSync(OUT, `// Generated by scripts/update-datacenter-ranges.mjs on ${today}. Do not edit by hand.
// Sources: ${loaded.join('; ')}.
// Each entry is "start-end" in base 36 (inclusive), merged and sorted.

export const DATACENTER_RANGES_UPDATED = '${today}';
export const DATACENTER_RANGES_SOURCES: readonly string[] = ${JSON.stringify(loaded)};
export const DATACENTER_V4 = [
${chunk(m4)},
].join('');
export const DATACENTER_V6 = [
${chunk(m6)},
].join('');
`);
console.log(`wrote ${m4.length} IPv4 and ${m6.length} IPv6 ranges to ${OUT}`);
