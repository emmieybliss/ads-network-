# Start the local BlissNova demo with Docker Compose (Windows PowerShell).
#   web + dashboards  http://localhost:3000
#   API               http://localhost:4000
#   demo publisher    http://localhost:3100
# First run generates .env.demo (random secrets and demo password, gitignored).
$ErrorActionPreference = 'Stop'
Set-Location (Join-Path $PSScriptRoot '..')

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) { Write-Host 'Docker is not installed. Install Docker Desktop first.'; exit 1 }
docker info *> $null
if ($LASTEXITCODE -ne 0) { Write-Host 'Docker Desktop is not running. Start it and try again.'; exit 1 }

function New-RandomBase64([int]$bytes) {
  $b = New-Object byte[] $bytes
  [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b)
  [Convert]::ToBase64String($b)
}
function New-RandomAlnum([int]$len) { (New-RandomBase64 64) -replace '[^A-Za-z0-9]', '' | ForEach-Object { $_.Substring(0, $len) } }

if (-not (Test-Path .env.demo)) {
  Write-Host 'Creating .env.demo with fresh random secrets...'
  @(
    '# Generated by scripts/start-demo.ps1 for the LOCAL DEMO only. Never use in production.'
    "POSTGRES_PASSWORD=$(New-RandomAlnum 24)"
    "APP_SECRET=$(New-RandomBase64 48)"
    "ENCRYPTION_KEY=$(New-RandomBase64 32)"
    "TRACKING_TOKEN_KEYS=k1:$(New-RandomBase64 32)"
    "SEED_PASSWORD=Demo-$(New-RandomAlnum 12)"
    'DEMO_SITE_KEY=pk_DemoLocalPublisherSite01'
  ) | Set-Content -Encoding ascii .env.demo
}

docker compose --env-file .env.demo up -d --build @args
if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }

Write-Host 'Waiting for the services to report healthy...'
$ready = $false
for ($i = 0; $i -lt 90 -and -not $ready; $i++) {
  try {
    $ok = @('http://localhost:3000/', 'http://localhost:4000/ready', 'http://localhost:3100/healthz') | ForEach-Object {
      (Invoke-WebRequest -UseBasicParsing -TimeoutSec 3 $_).StatusCode -eq 200
    }
    $ready = -not ($ok -contains $false)
  } catch { $ready = $false }
  if (-not $ready) { Start-Sleep -Seconds 2 }
}
if (-not $ready) { Write-Host 'The demo did not become healthy in time. See docs/TROUBLESHOOTING.md.'; exit 1 }

$pw = ((Get-Content .env.demo) | Where-Object { $_ -like 'SEED_PASSWORD=*' }) -replace '^SEED_PASSWORD=', ''
Write-Host ""
Write-Host "BlissNova demo is running."
Write-Host "  Website and dashboards   http://localhost:3000"
Write-Host "  API health               http://localhost:4000/ready"
Write-Host "  Demo publisher site      http://localhost:3100"
Write-Host "  Logins                   admin@example.com / advertiser@example.com / publisher@example.com"
Write-Host "  Password                 $pw   (stored in .env.demo)"
Write-Host "All accounts, campaigns and statistics are fictional demo data."
